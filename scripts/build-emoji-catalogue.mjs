#!/usr/bin/env node
/**
 * Builds the emoji the search can offer, from a published set rather than from
 * memory: `emojilib` (MIT) holds the emoji and the words people look for them
 * by, and `household-emoji.ts` holds the hand-written words for the things a
 * shelf actually holds.
 *
 * Two decisions worth knowing about:
 *
 *  - **Only single characters get through.** A symbol is kept when it is one
 *    code point, or one plus the variation selector that asks for the coloured
 *    drawing of it. The joined-up sequences (🧑‍🍳, 🏳️‍🌈) are drawn differently on
 *    every platform and look broken wherever the fonts disagree, and flags are
 *    two code points that a bare name cannot carry well.
 *  - **The household list wins on wording, and leads on order.** Its keywords
 *    come first for the emoji it names, and those emoji are listed before the
 *    rest, so a search that could mean either the everyday thing or an obscure
 *    one offers the everyday thing first.
 *
 * Run with `npm run build:catalogue`. `tests/emoji.test.ts` fails if the
 * generated file is out of step with the data, so this cannot go stale quietly.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { HOUSEHOLD_EMOJI } from '../src/data/household-emoji.ts';

const ROOT = resolve(import.meta.dirname, '..');
const DATASET = resolve(ROOT, 'node_modules/emojilib/dist/emoji-en-US.json');
const OUTPUT = resolve(ROOT, 'src/data/emoji-catalogue.ts');

/** How many of the published keywords to keep for each emoji. */
const KEYWORDS_PER_EMOJI = 5;

/**
 * One character, or one plus its variation selector: no zero-width joiners, no
 * skin tones, no flags.
 */
function isSingleCharacter(symbol) {
  const characters = [...symbol];
  return (
    characters.length <= 2 &&
    (characters.length === 1 || characters[1] === '\uFE0F') &&
    !symbol.includes('\u200d')
  );
}

/** "roll_of_paper" is the dataset's spelling of "roll of paper". */
function words(keyword) {
  return keyword.replace(/_/gu, ' ').trim().toLowerCase();
}

/**
 * The whole catalogue, household entries first, then the rest of the set.
 * Exported for the test that keeps the generated file honest.
 */
export function buildCatalogue(dataset) {
  const household = HOUSEHOLD_EMOJI.map((option) => option.symbol);
  const chosen = new Map();

  for (const [symbol, keywords] of Object.entries(dataset)) {
    if (isSingleCharacter(symbol)) {
      chosen.set(symbol, keywords.map(words).filter((word) => word !== ''));
    }
  }

  // The household words come first for the emoji it names: they are the ones a
  // person is most likely to type.
  for (const option of HOUSEHOLD_EMOJI) {
    const published = chosen.get(option.symbol) ?? [];
    chosen.set(option.symbol, [...option.keywords, ...published]);
  }

  const ordered = [
    ...household,
    ...[...chosen.keys()].filter((symbol) => !household.includes(symbol)),
  ];

  return ordered.map((symbol) => ({
    symbol,
    keywords: [...new Set(chosen.get(symbol) ?? [])].slice(0, KEYWORDS_PER_EMOJI + 4),
  }));
}

function sourceOf(catalogue) {
  const rows = catalogue.map(
    (option) =>
      `  { symbol: ${JSON.stringify(option.symbol)}, keywords: [${option.keywords
        .map((keyword) => JSON.stringify(keyword))
        .join(', ')}] },`,
  );

  return `import type { EmojiOption } from './emoji';

/**
 * Generated by \`npm run build:catalogue\` from emojilib (MIT) and
 * \`household-emoji.ts\`. Do not edit by hand: edit the household words, or the
 * generator, and run it again.
 *
 * ${catalogue.length} emoji, each one drawn by a single character so that every
 * platform draws it the same way.
 */
export const EMOJI_CATALOGUE: readonly EmojiOption[] = [
${rows.join('\n')}
];
`;
}

async function main() {
  const dataset = JSON.parse(await readFile(DATASET, 'utf8'));
  const catalogue = buildCatalogue(dataset);
  await writeFile(OUTPUT, sourceOf(catalogue));
  console.log(`Wrote ${catalogue.length} emoji to ${OUTPUT.replace(`${ROOT}/`, '')}.`);
}

if (process.argv[1]?.endsWith('build-emoji-catalogue.mjs') === true) {
  await main();
}
